import { defineComponent } from 'vue'
import { NButton, NIcon } from 'naive-ui'
import { useI18n } from 'vue-i18n'
import { useThemeStore } from '@/store/theme/theme'
import styles from './index.module.scss'

const SunIcon = () => (
  <svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">
    <circle cx="12" cy="12" r="5"></circle>
    <line x1="12" y1="1" x2="12" y2="3"></line>
    <line x1="12" y1="21" x2="12" y2="23"></line>
    <line x1="4.22" y1="4.22" x2="5.64" y2="5.64"></line>
    <line x1="18.36" y1="18.36" x2="19.78" y2="19.78"></line>
    <line x1="1" y1="12" x2="3" y2="12"></line>
    <line x1="21" y1="12" x2="23" y2="12"></line>
    <line x1="4.22" y1="19.78" x2="5.64" y2="18.36"></line>
    <line x1="18.36" y1="5.64" x2="19.78" y2="4.22"></line>
  </svg>
)

const MoonIcon = () => (
  <svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">
    <path d="M21 12.79A9 9 0 1 1 11.21 3 7 7 0 0 0 21 12.79z"></path>
  </svg>
)

const Theme = defineComponent({
  name: 'Theme',
  setup() {
    const { t } = useI18n()
    const themeStore = useThemeStore()

    return { t, themeStore }
  },
  render() {
    return (
      <NButton
        class={styles.theme}
        quaternary
        onClick={() => (this.themeStore.darkTheme = !this.themeStore.darkTheme)}
        title={this.t(this.themeStore.darkTheme ? 'theme.light' : 'theme.dark')}
      >
        {{
          icon: () => <NIcon size="16">{this.themeStore.darkTheme ? <MoonIcon /> : <SunIcon />}</NIcon>
        }}
      </NButton>
    )
  }
})

export default Theme
